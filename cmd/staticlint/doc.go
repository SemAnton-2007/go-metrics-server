/*
Пакет staticlint содержит multichecker для статического анализа кода.

Мультичекер объединяет:

1. Стандартные анализаторы из golang.org/x/tools/go/analysis/passes
2. Все анализаторы класса SA из staticcheck.io
3. Публичные анализаторы:
  - bodyclose: проверяет закрытие тел HTTP-ответов
  - errcheck: обнаруживает необработанные ошибки

4. Кастомный анализатор noexit: запрещает прямой вызов os.Exit в main

Запуск:

	go run cmd/staticlint/*.go ./...

Анализаторы:

Стандартные анализаторы (golang.org/x/tools/go/analysis/passes):

	asmdecl      - проверка соответствия ассемблерных деклараций
	assign       - обнаружение бесполезных присваиваний
	atomic       - проверка использования пакета sync/atomic
	bools        - обнаружение ошибок в логических операциях
	buildtag     - проверка корректности тегов сборки
	cgocall      - проверка правил вызова CGO
	composite    - проверка композитных литералов
	copylock     - проверка блокировок копирования
	errorsas     - проверка передачи ошибок в errors.As
	httpresponse - проверка обработки HTTP-ответов
	loopclosure  - обнаружение захвата переменных в замыканиях
	lostcancel   - проверка отмены контекста
	nilfunc      - обнаружение сравнения функций с nil
	printf       - проверка форматированных строк
	shift        - проверка сдвигов
	structtag    - проверка тегов структур
	tests        - обнаружение ошибок в тестах
	unmarshal    - проверка разбора сообщений
	unreachable  - обнаружение недостижимого кода
	unsafeptr    - проверка использования unsafe.Pointer
	unusedresult - проверка неиспользованных результатов

Анализаторы staticcheck класса SA:

	SA1xxx - общие проверки корректности
	SA2xxx - проверки стиля кодирования
	SA3xxx - проверки работы с объектами
	SA4xxx - проверки безопасности
	SA5xxx - проверки производительности
	SA6xxx - проверки надежности

Публичные анализаторы:

	bodyclose - проверяет закрытие тел HTTP-ответов
	errcheck  - обнаруживает необработанные ошибки

Кастомный анализатор:

	noexit - запрещает прямой вызов os.Exit в функции main пакета main
*/
